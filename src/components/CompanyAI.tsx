import { useEffect, useRef, useState, type FormEvent } from 'react'
import { MessageSquare, RefreshCw, Send, Sparkles } from 'lucide-react'
import { api, type CompanyAIInsights, type CompanyChatTurn } from '../api/client'

const errorText = (e: unknown) => {
  const raw = e instanceof Error ? e.message : ''
  try {
    const detail = JSON.parse(raw).detail
    if (typeof detail === 'string') return detail
  } catch {
    /* plain message */
  }
  return raw || 'The AI is not available right now.'
}

export function CompanyInsights({ period }: { period?: string }) {
  const [result, setResult] = useState<CompanyAIInsights | null>(null)
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(true)

  const regenerate = () => {
    setLoading(true)
    setError('')
    api
      .companyInsights(period, true)
      .then(setResult)
      .catch((e) => setError(errorText(e)))
      .finally(() => setLoading(false))
  }

  useEffect(() => {
    let active = true
    api
      .companyInsights(period)
      .then((r) => active && setResult(r))
      .catch((e) => active && setError(errorText(e)))
      .finally(() => active && setLoading(false))
    return () => {
      active = false
    }
  }, [period])

  return (
    <section className="insight-panel">
      <div className="insight-header">
        <div className="insight-title">
          <span>
            <Sparkles size={18} />
          </span>
          <div>
            <p className="eyebrow">AI INSIGHTS</p>
            <h2>Interpretation of the report</h2>
          </div>
        </div>
        <button type="button" className="ai-retry" onClick={regenerate} disabled={loading}>
          <RefreshCw size={13} className={loading ? 'spin' : undefined} />
          Regenerate
        </button>
      </div>
      {loading && !result && <p className="ai-state">Generating insights…</p>}
      {error && <p className="ai-state ai-state--error">{error}</p>}
      {result && (
        <div className="bd-insights">
          {result.insights.map((item, i) => (
            <article key={item.title}>
              <span>{String(i + 1).padStart(2, '0')}</span>
              <div>
                <strong>{item.title}</strong>
                <p>{item.text}</p>
              </div>
            </article>
          ))}
        </div>
      )}
      <p className="ai-disclaimer">Generated by AI from the report content; not quotations. Verify before relying on it.</p>
    </section>
  )
}

export function CompanyChat({ period }: { period?: string }) {
  const [turns, setTurns] = useState<CompanyChatTurn[]>([])
  const [input, setInput] = useState('')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')
  const box = useRef<HTMLDivElement>(null)

  useEffect(() => {
    box.current?.scrollTo({ top: box.current.scrollHeight })
  }, [turns, busy])

  const submit = async (e: FormEvent) => {
    e.preventDefault()
    const message = input.trim()
    if (!message || busy) return
    const history = turns
    setTurns([...history, { role: 'user', content: message }])
    setInput('')
    setBusy(true)
    setError('')
    try {
      const answer = await api.companyChat(message, history, period)
      setTurns((t) => [...t, { role: 'assistant', content: answer }])
    } catch (err) {
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  return (
    <section className="insight-panel ai-chat">
      <div className="insight-header">
        <div className="insight-title">
          <span>
            <MessageSquare size={18} />
          </span>
          <div>
            <p className="eyebrow">ASK THE REPORT</p>
            <h2>AI assistant</h2>
          </div>
        </div>
      </div>
      <div className="ai-chat__messages" ref={box}>
        {turns.length === 0 && (
          <p className="ai-state">Ask about customers, milestones, strategy or the financials in this report.</p>
        )}
        {turns.map((t, i) => (
          <div key={i} className={`ai-chat__msg ${t.role}`}>
            {t.content}
          </div>
        ))}
        {busy && <div className="ai-chat__msg assistant">Thinking…</div>}
        {error && <p className="ai-state ai-state--error">{error}</p>}
      </div>
      <form className="ai-chat__form" onSubmit={submit}>
        <input
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder="e.g. Which customers signed in the half-year?"
          maxLength={1500}
          disabled={busy}
        />
        <button type="submit" disabled={busy || !input.trim()} aria-label="Send">
          <Send size={15} />
        </button>
      </form>
      <p className="ai-disclaimer">Answers are generated by AI using only this report&apos;s data.</p>
    </section>
  )
}
